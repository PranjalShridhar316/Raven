#ifndef EDITOR_H
#define EDITOR_H

/*
 * ============================================================================
 * Raven Editor
 * File        : editor.h
 * Description : Global editor state.
 * ============================================================================
 */

#ifndef _POSIX_C_SOURCE
#define _POSIX_C_SOURCE 200809L
#endif

#include "row.h"

/*
 * ============================================================================
 * Editor Configuration
 * ============================================================================
 */

typedef struct
{
    /*
     * ------------------------------------------------------------------------
     * Cursor Position
     * ------------------------------------------------------------------------
     */

    int cx;
    int cy;

    /*
     * Rendered Cursor Position
     *
     * (Used when tabs and UTF-8 rendering are implemented.)
     */

    int rx;

    /*
     * ------------------------------------------------------------------------
     * Screen Size
     * ------------------------------------------------------------------------
     */

    int screenrows;
    int screencols;

    /*
     * ------------------------------------------------------------------------
     * Scroll Offsets
     * ------------------------------------------------------------------------
     */

    int rowoff;
    int coloff;

    /*
     * ------------------------------------------------------------------------
     * Document
     * ------------------------------------------------------------------------
     */

    int numRows;
    EditorRow *rows;

    /*
     * ------------------------------------------------------------------------
     * Current File
     * ------------------------------------------------------------------------
     */

    char *filename;

    /*
     * ------------------------------------------------------------------------
     * Editor State
     * ------------------------------------------------------------------------
     */

    int dirty;

} EditorConfig;

/*
 * ============================================================================
 * Global Editor Instance
 * ============================================================================
 */

extern EditorConfig E;

/*
 * ============================================================================
 * Editor Functions
 * ============================================================================
 */

/*
 * Initialize the editor.
 */
void editorInit(void);

/*
 * Release all editor resources.
 */
void editorFree(void);

#endif /* EDITOR_H */