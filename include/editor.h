#ifndef EDITOR_H
#define EDITOR_H

/*
 * ============================================================================
 * Raven Editor
 * File        : editor.h
 * Description : Global editor state.
 * ============================================================================
 */

#include "row.h"

/*
 * ============================================================================
 * Editor Configuration
 * ============================================================================
 */

typedef struct
{
    /*
     * ------------------------------------------------------------------------
     * Cursor Position
     * ------------------------------------------------------------------------
     */

    int cx;
    int cy;

    /*
     * ------------------------------------------------------------------------
     * Screen Size
     * ------------------------------------------------------------------------
     */

    int screenrows;
    int screencols;

    /*
     * ------------------------------------------------------------------------
     * Scroll Offsets
     * ------------------------------------------------------------------------
     */

    int rowoff;
    int coloff;

    /*
     * ------------------------------------------------------------------------
     * Document Buffer
     * ------------------------------------------------------------------------
     */

    int numRows;
    EditorRow *rows;

    /*
     * ------------------------------------------------------------------------
     * File Information
     * ------------------------------------------------------------------------
     */

    char *filename;

    /*
     * ------------------------------------------------------------------------
     * Dirty Flag
     *
     * 0 = Clean
     * 1 = Modified
     * ------------------------------------------------------------------------
     */

    int dirty;

} EditorConfig;

/*
 * ============================================================================
 * Global Editor Instance
 * ============================================================================
 */

extern EditorConfig E;

/*
 * ============================================================================
 * Editor Functions
 * ============================================================================
 */

/*
 * Initialize editor.
 */
void editorInit(void);

/*
 * Release editor resources.
 */
void editorFree(void);

#endif /* EDITOR_H */