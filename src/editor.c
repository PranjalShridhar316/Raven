/*
 * ============================================================================
 * Raven Editor
 * File        : editor.c
 * Description : Editor initialization and cleanup.
 * ============================================================================
 */

#include <stdlib.h>

#include "editor.h"
#include "terminal.h"
#include "buffer.h"

/*
 * ============================================================================
 * Global Editor State
 * ============================================================================
 */

EditorConfig E;

/*
 * ============================================================================
 * Initialize Editor
 * ============================================================================
 */

void editorInit(void)
{
    /*
     * ------------------------------------------------------------------------
     * Cursor Position
     * ------------------------------------------------------------------------
     */

    E.cx = 0;
    E.cy = 0;

    /*
     * ------------------------------------------------------------------------
     * Screen Scrolling
     * ------------------------------------------------------------------------
     */

    E.rowoff = 0;
    E.coloff = 0;

    /*
     * ------------------------------------------------------------------------
     * Document
     * ------------------------------------------------------------------------
     */

    E.numRows = 0;
    E.rows = NULL;

    /*
     * ------------------------------------------------------------------------
     * File Information
     * ------------------------------------------------------------------------
     */

    E.filename = NULL;

    /*
     * ------------------------------------------------------------------------
     * Dirty Flag
     * ------------------------------------------------------------------------
     */

    E.dirty = 0;

    /*
     * ------------------------------------------------------------------------
     * Terminal Size
     * ------------------------------------------------------------------------
     */

    if (getWindowSize(&E.screenrows, &E.screencols) == -1)
    {
        exit(EXIT_FAILURE);
    }

    /*
     * ------------------------------------------------------------------------
     * Temporary Test Data
     *
     * These rows are only for testing.
     * They will be removed once file loading is implemented.
     * ------------------------------------------------------------------------
     */

    editorInsertRow(0, "Welcome to Raven", 16);
    editorInsertRow(1, "Milestone 2.0", 13);
    editorInsertRow(2, "Document Buffer Engine", 22);

    /*
     * Loading the default text should not mark the file as modified.
     */

    E.dirty = 0;
}

/*
 * ============================================================================
 * Free Editor Resources
 * ============================================================================
 */

void editorFree(void)
{
    editorFreeBuffer();

    free(E.filename);
    E.filename = NULL;

    E.dirty = 0;
}